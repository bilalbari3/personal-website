const zero = (): Macros => ({ netCarbs: 0, fat: 0, protein: 0, calories: 0 });

/** Per-serving macros computed from the food database. */
export function recipeMacros(recipe: Recipe): Macros {
  const total = recipe.ingredients.reduce((acc, ing) => {
    if (!ing.foodId) return acc;
    const food = getFood(ing.foodId);
    if (!food) return acc;
    const s = ing.servings ?? 1;
    acc.netCarbs += food.macros.netCarbs * s;
    acc.fat += food.macros.fat * s;
    acc.protein += food.macros.protein * s;
    acc.calories += food.macros.calories * s;
    return acc;
  }, zero());
  return {
    netCarbs: round1(total.netCarbs / recipe.serves),
    fat: round1(total.fat / recipe.serves),
    protein: round1(total.protein / recipe.serves),
    calories: Math.round(total.calories / recipe.serves),
  };
}

function round1(n: number) {
  return Math.round(n * 10) / 10;
}

